export function itemIcon(item: ItemId): PixelBuffer {
  return fromAscii(ICONS[item], P).outline(C.outline);
}

export function allItemIcons(): Record<ItemId, PixelBuffer> {
  return Object.fromEntries((Object.keys(ICONS) as ItemId[]).map((id) => [id, itemIcon(id)])) as Record<ItemId, PixelBuffer>;
}

